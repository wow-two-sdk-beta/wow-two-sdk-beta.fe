/* ---------------------------------------------------------------------------
 * CSS emitter — turn a Theme into scoped class blocks.
 *
 * An app applies a theme by adding `theme-{id}` to a root element. The emitted
 * CSS overrides the lib's semantic `--color-*` vars (and optional `--radius-*`)
 * under that class, so every Tailwind utility (`bg-primary`, `text-foreground`,
 * …) re-resolves to the theme's values. Dark mode reuses the lib's variant:
 * `.dark.theme-{id}` (i.e. `.dark` + the theme class on the same element, or an
 * ancestor `.dark`).
 * ------------------------------------------------------------------------- */

import type { Theme, ThemeGlassTokens, ThemeStatus } from './Theme';
import { SemanticTokens, type TokenSet } from './Tokens';

/** Radius knob → concrete `--radius-*` triple (mirrors the lib's default scale shifts). */
const RadiusScale: Record<NonNullable<Theme['radius']>, Record<string, string>> = {
  sm: { md: '0.375rem', lg: '0.5rem', xl: '0.75rem' },
  md: { md: '0.5rem', lg: '0.75rem', xl: '1rem' },
  lg: { md: '0.625rem', lg: '0.875rem', xl: '1.25rem' },
};

/** Render one token set as `  --color-{key}: {value};` declaration lines. */
function declarations(set: TokenSet, indent = '  '): string {
  return SemanticTokens.map((tok) => `${indent}--color-${tok}: ${set[tok]};`).join('\n');
}

/** Render the optional radius overrides as declaration lines (empty string when unset). */
function radiusDeclarations(theme: Theme, indent = '  '): string {
  if (!theme.radius) return '';
  const scale = RadiusScale[theme.radius];
  return (
    '\n' +
    Object.entries(scale)
      .map(([k, v]) => `${indent}--radius-${k}: ${v};`)
      .join('\n')
  );
}

/** Render the optional ambient backdrop as a declaration line (empty string when unset). */
function ambientDeclaration(layers: string | undefined, indent = '  '): string {
  return layers ? `\n${indent}--theme-ambient: ${layers};` : '';
}

/** The custom property each glass token writes, in emission order. */
const GlassProperties: ReadonlyArray<readonly [keyof ThemeGlassTokens, string]> = [
  ['fill', '--glass-fill'],
  ['sideFill', '--glass-side-fill'],
  ['menuFill', '--glass-menu-fill'],
  ['blur', '--glass-blur'],
  ['saturate', '--glass-saturate'],
  ['edge', '--glass-edge'],
  ['highlight', '--glass-highlight'],
  ['shadow', '--glass-shadow'],
  ['bottomShadow', '--glass-bottom-shadow'],
  ['menuShadow', '--glass-menu-shadow'],
];

/** The tokens that are shadows; each ends in the highlight line. */
const GlassShadowTokens: ReadonlySet<keyof ThemeGlassTokens> = new Set(['shadow', 'bottomShadow', 'menuShadow']);

/**
 * Render one mode's glass strength as declaration lines (empty string when unset). With a highlight, every shadow
 * ends in its 1px inset line along the top edge, so a surface that takes a shadow takes the highlight too.
 */
function glassDeclarations(tokens: ThemeGlassTokens | undefined, indent = '  '): string {
  if (!tokens) return '';
  const lines: Array<string> = [];
  for (const [key, property] of GlassProperties) {
    const value = tokens[key];
    if (value === undefined) continue;
    const declared =
      GlassShadowTokens.has(key) && tokens.highlight !== undefined
        ? `${value}, inset 0 1px 0 var(--glass-highlight)`
        : value;
    lines.push(`\n${indent}${property}: ${declared};`);
  }
  return lines.join('');
}

/**
 * Emit the CSS for a single theme: a light `.theme-{id}` block + a
 * `.dark.theme-{id}` block. Returns a string (no trailing newline).
 */
export function themeToCss(theme: Theme): string {
  const radius = radiusDeclarations(theme);
  const id = theme.id.replace(/[^a-zA-Z0-9_-]/gu, (character) => `\\${character.codePointAt(0)!.toString(16)} `);
  const selector = `.theme-${id}`;
  const light =
    `${selector} {\n${declarations(theme.light)}${radius}${ambientDeclaration(theme.ambient?.light)}` +
    `${glassDeclarations(theme.glass?.light)}\n}`;
  const dark =
    `.dark${selector}, .dark ${selector} {\n${declarations(theme.dark)}${ambientDeclaration(theme.ambient?.dark)}` +
    `${glassDeclarations(theme.glass?.dark)}\n}`;
  return `${light}\n\n${dark}`;
}

/** Emit a full stylesheet for many themes, with a generated-file banner. */
export function emitAllThemesCss(themes: ReadonlyArray<Theme>): string {
  const banner =
    '/* Generated by @wow-two-beta/fe theme engine — do not edit by hand.\n' +
    ' * Source: src/foundation/themes/Registry.ts → regenerate via the package build. */\n';
  const body = themes.map(themeToCss).join('\n\n');
  return `${banner}\n${body}\n`;
}

/** Machine-readable manifest entry for one theme (no token payload — index only). */
export interface ThemeManifestEntry {
  id: string;
  name: string;
  description: string;
  tags: ReadonlyArray<string>;
  /** Lifecycle status — `validated` (real-app proven) or `candidate` (engine-proven). */
  status: ThemeStatus;
  contrastAA: boolean;
}

/** Build the `themes.json` manifest payload from the registry. */
export function emitThemesManifest(themes: ReadonlyArray<Theme>): ReadonlyArray<ThemeManifestEntry> {
  return themes.map((t) => ({
    id: t.id,
    name: t.name,
    description: t.description,
    tags: t.tags,
    status: t.status,
    contrastAA: t.meta.contrastAA,
  }));
}
